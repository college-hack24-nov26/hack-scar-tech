
from pathlib import Path

import joblib
import pandas as pd

MODEL_PATH = (
    Path(__file__).resolve().parent.parent
    / "ml"
    / "models"
    / "heat_loss_models.joblib"
)

if not MODEL_PATH.exists():
    raise FileNotFoundError(f"ML model not found: {MODEL_PATH}")

model_bundle = joblib.load(MODEL_PATH)

model = model_bundle["model"]
FEATURES = model_bundle["features"]
TARGETS = model_bundle["targets"]


def predict_heat_loss(shelter: dict, climate: dict) -> dict:
    length = shelter["length_m"]
    width = shelter["width_m"]
    height = shelter["height_m"]

    wall_area = (
        2 * (length + width) * height
        - shelter.get("window_area_m2", 0)
        - shelter.get("door_area_m2", 0)
    )

    roof_area = length * width
    floor_area = length * width

    if wall_area <= 0:
        raise ValueError("Calculated wall area must be positive.")

    temperature_difference = (
        20 - climate["outdoor_temperature_c"]
    )

    input_data = {
        "length_m": length,
        "width_m": width,
        "height_m": height,
        "wall_u_value": shelter["wall_u_value"],
        "roof_u_value": shelter["roof_u_value"],
        "floor_u_value": shelter["floor_u_value"],
        "window_area_m2": shelter.get("window_area_m2", 0),
        "door_area_m2": shelter.get("door_area_m2", 0),
        "outdoor_temperature_c": climate["outdoor_temperature_c"],
        "wall_area_m2": wall_area,
        "roof_area_m2": roof_area,
        "floor_area_m2": floor_area,
        "temperature_difference_c": temperature_difference,
    }

    input_df = pd.DataFrame(
        [[input_data[feature] for feature in FEATURES]],
        columns=FEATURES,
    )

    predictions = model.predict(input_df)[0]

    prediction_results = {
        target: round(float(value), 2)
        for target, value in zip(TARGETS, predictions)
    }

    return {
        "model_name": model_bundle["model_name"],
        "predictions": prediction_results,
        "input_features": input_data,
        "notice": (
            "Predictions are generated by a model trained on "
            "synthetic thermal simulation data. They are not "
            "validated real-world measurements."
        ),
    }

